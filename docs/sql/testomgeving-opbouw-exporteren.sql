-- Testomgeving (docs/REFERRAL_AUTOMATISERING.md, stap 2). Uitvoeren in de SQL Editor van het ECHTE Arnobot-project.
--
-- Dit bestand LEEST ALLEEN en wijzigt niets. Het leest geen rijen uit tabellen, alleen de opbouw van het schema public.
-- De uitkomst is een cel met SQL. Die voer je uit in de SQL Editor van het project arnobot-test (nooit in het echte).
-- De eerste regels van die uitkomst weigeren te draaien als er al tabellen staan.

with
mijn_tabellen as (
  select c.oid, c.relname, c.relrowsecurity from pg_class c
  where c.relnamespace = 'public'::regnamespace and c.relkind in ('r', 'p')
    and not exists (select 1 from pg_depend d where d.classid = 'pg_class'::regclass and d.objid = c.oid and d.deptype = 'e')
),
mijn_functies as (
  select p.oid from pg_proc p
  where p.pronamespace = 'public'::regnamespace and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.classid = 'pg_proc'::regclass and d.objid = p.oid and d.deptype = 'e')
),
delen(stap, naam, tekst) as (
  select 0, '', $x$do $slot$ begin
  if exists (select 1 from pg_tables where schemaname = 'public') then
    raise exception 'STOP: hier staan al tabellen. Dit hoort alleen in een leeg testproject.';
  end if;
end $slot$;
set local check_function_bodies = off;$x$

  union all
  select 1, e.extname, format('create extension if not exists %I with schema %I;', e.extname, n.nspname)
  from pg_extension e join pg_namespace n on n.oid = e.extnamespace
  where e.extname in ('vector', 'pg_trgm', 'unaccent', 'uuid-ossp', 'pgcrypto', 'citext')

  union all
  select 2, t.typname, format('create type public.%I as enum (%s);', t.typname,
    (select string_agg(quote_literal(v.enumlabel), ', ' order by v.enumsortorder) from pg_enum v where v.enumtypid = t.oid))
  from pg_type t where t.typnamespace = 'public'::regnamespace and t.typtype = 'e'

  -- Losse tellers en die van serial-kolommen. Tellers van identity-kolommen ontstaan met de tabel zelf.
  union all
  select 3, c.relname, format('create sequence public.%I;', c.relname)
  from pg_class c
  where c.relnamespace = 'public'::regnamespace and c.relkind = 'S'
    and not exists (select 1 from pg_depend d where d.classid = 'pg_class'::regclass and d.objid = c.oid and d.deptype in ('i', 'e'))

  union all
  select 4, t.relname, format(E'create table public.%I (\n  %s\n);', t.relname,
    (select string_agg(format('%I %s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
        case a.attidentity when 'a' then ' generated always as identity' when 'd' then ' generated by default as identity' else '' end,
        case when a.attnotnull then ' not null' else '' end), E',\n  ' order by a.attnum)
      from pg_attribute a where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped))
  from mijn_tabellen t

  union all
  select 5, f.oid::regprocedure::text, pg_get_functiondef(f.oid) || ';'
  from mijn_functies f

  -- Standaardwaarden en berekende kolommen pas na de functies: ze kunnen er een gebruiken.
  union all
  select 6, t.relname || '.' || a.attname,
    case when a.attgenerated = 's'
      then format(E'alter table public.%I drop column %I;\nalter table public.%I add column %I %s generated always as (%s) stored;',
        t.relname, a.attname, t.relname, a.attname, format_type(a.atttypid, a.atttypmod), pg_get_expr(d.adbin, d.adrelid))
      else format('alter table public.%I alter column %I set default %s;', t.relname, a.attname, pg_get_expr(d.adbin, d.adrelid))
    end
  from mijn_tabellen t
  join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
  join pg_attrdef d on d.adrelid = t.oid and d.adnum = a.attnum

  -- Eerst sleutels en controles, daarna pas de verwijzingen tussen tabellen.
  union all
  select case when c.contype = 'f' then 8 else 7 end, t.relname || '.' || c.conname,
    format('alter table public.%I add constraint %I %s;', t.relname, c.conname, pg_get_constraintdef(c.oid))
  from mijn_tabellen t join pg_constraint c on c.conrelid = t.oid
  where c.contype in ('p', 'u', 'c', 'x', 'f')

  union all
  select case when i.indisunique then 7 else 9 end, ic.relname, pg_get_indexdef(i.indexrelid) || ';'
  from mijn_tabellen t
  join pg_index i on i.indrelid = t.oid
  join pg_class ic on ic.oid = i.indexrelid
  where not exists (select 1 from pg_constraint c where c.conindid = i.indexrelid and c.contype in ('p', 'u', 'x'))

  union all
  select 10, lpad(c.oid::bigint::text, 12, '0'), format(E'create view public.%I as\n%s', c.relname, pg_get_viewdef(c.oid, true))
  from pg_class c where c.relnamespace = 'public'::regnamespace and c.relkind = 'v'
    and not exists (select 1 from pg_depend d where d.classid = 'pg_class'::regclass and d.objid = c.oid and d.deptype = 'e')

  union all
  select 11, g.tgname, pg_get_triggerdef(g.oid) || ';'
  from mijn_tabellen t join pg_trigger g on g.tgrelid = t.oid
  where not g.tgisinternal

  union all
  select 12, t.relname, format('alter table public.%I enable row level security;', t.relname)
  from mijn_tabellen t where t.relrowsecurity

  union all
  select 13, p.tablename || '.' || p.policyname,
    format('create policy %I on public.%I as %s for %s to %s%s%s;', p.policyname, p.tablename, p.permissive, p.cmd,
      array_to_string(p.roles, ', '),
      coalesce(' using (' || p.qual || ')', ''), coalesce(' with check (' || p.with_check || ')', ''))
  from pg_policies p where p.schemaname = 'public'

  -- Functies die in het echte project niet voor de publieke sleutel zijn, ook hier dichtzetten.
  union all
  select 14, f.oid::regprocedure::text,
    format(E'revoke execute on function %s from public, anon, authenticated;\ngrant execute on function %s to service_role;',
      f.oid::regprocedure, f.oid::regprocedure)
  from mijn_functies f
  where not has_function_privilege('anon', f.oid, 'execute')

  union all
  select 15, '', $x$notify pgrst, 'reload schema';
select (select count(*) from pg_tables where schemaname = 'public') as tabellen;$x$
)
select
  (select count(*) from mijn_tabellen) as aantal_tabellen,
  E'begin;\n\n' || (select string_agg(tekst, E'\n\n' order by stap, naam) from delen where stap < 15)
    || E'\n\ncommit;\n\n' || (select tekst from delen where stap = 15) as kopieer_deze_cel;
